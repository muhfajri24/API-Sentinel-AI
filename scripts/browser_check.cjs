/* Optional real-browser QA. Requires Playwright and a local Chromium executable. */
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'evidence', 'browser');
fs.mkdirSync(out, {recursive: true});
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
 const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
 const started = Date.now();
 const findings = [];
 try {
  const context = await browser.newContext({viewport:{width:1440,height:1100}, recordVideo:{dir:out,size:{width:1440,height:1100}}, acceptDownloads:true});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8501', {waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'API Sentinel AI',exact:true}).waitFor();
  await page.getByText('OFFLINE FIXTURE MODE', {exact:false}).waitFor();
  await page.screenshot({path:path.join(out,'desktop-start.png'),fullPage:true});
  await pause(5000);
  await page.getByRole('button',{name:'1. Generate test plan',exact:true}).click();
  const execute = page.getByRole('button',{name:'2. Execute local tests',exact:true});
  await execute.waitFor(); assert(await execute.isDisabled());
  await page.getByText('Review complete requests and expected JSON',{exact:true}).scrollIntoViewIfNeeded();
  await pause(7000);
  await page.getByRole('checkbox',{name:'I reviewed the expected outcomes against the OpenAPI and business rule.',exact:true}).check();
  await page.getByRole('checkbox',{name:'I own/control the local test environment and authorize these requests.',exact:true}).check();
  await execute.click();
  await page.getByRole('heading',{name:'3 · Observed execution evidence',exact:true}).waitFor();
  await page.getByRole('heading',{name:'3 · Observed execution evidence',exact:true}).scrollIntoViewIfNeeded();
  await page.getByText('FAIL — overdraft-rule',{exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'desktop-evidence.png'),fullPage:true});
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download evidence (JSON)',exact:true}).click();
  const download=await downloadPromise;
  await download.saveAs(path.join(out,'downloaded-receipt.json'));
  const receipt = JSON.parse(fs.readFileSync(path.join(out,'downloaded-receipt.json'),'utf8'));
  assert.equal(receipt.source,'fixture');
  assert.deepEqual(receipt.results.map(x=>x.status),['PASS','FAIL']);
  const htmlPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download standalone report (HTML)',exact:true}).click();
  await (await htmlPromise).saveAs(path.join(out,'downloaded-report.html'));
  await page.keyboard.press('Tab');
  const focus = await page.evaluate(()=>({tag:document.activeElement.tagName,visible:!!document.activeElement.getBoundingClientRect().width}));
  assert(focus.visible && focus.tag !== 'BODY');
  await page.getByRole('textbox',{name:'Business rule',exact:true}).fill('An unsupported rule for stale-state verification');
  await page.getByRole('textbox',{name:'Business rule',exact:true}).press('Tab');
  await page.getByRole('button',{name:'1. Generate test plan',exact:true}).waitFor();
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).some(x=>x.textContent.includes('2. Execute local tests')));
  assert.equal(await page.getByRole('button',{name:'Download evidence (JSON)',exact:true}).count(),0);
  findings.push({check:'desktop_full_flow_downloads_keyboard_and_stale_state',status:'PASS',source:receipt.source,verdicts:receipt.results.map(x=>x.status)});
  // Hold the actual observed screen to make an unedited 60-second capture; no live-AI claim.
  await page.getByRole('textbox',{name:'Business rule',exact:true}).fill('Withdrawals exceeding the available balance must be rejected with HTTP 422 and approved=false.');
  await page.getByRole('textbox',{name:'Business rule',exact:true}).press('Tab');
  await page.getByRole('button',{name:'1. Generate test plan',exact:true}).click();
  await page.getByRole('checkbox',{name:'I reviewed the expected outcomes against the OpenAPI and business rule.',exact:true}).check();
  await page.getByRole('checkbox',{name:'I own/control the local test environment and authorize these requests.',exact:true}).check();
  await execute.click();
  await page.getByText('FAIL — overdraft-rule',{exact:true}).scrollIntoViewIfNeeded();
  await pause(Math.max(0,61000-(Date.now()-started)));
  assert.deepEqual(errors,[]);
  const video=page.video(); await context.close();
  await video.saveAs(path.join(out,'fixture-demo.webm'));
  const mobile = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const mp=await mobile.newPage();
  await mp.goto('http://127.0.0.1:8501',{waitUntil:'networkidle'});
  await mp.getByRole('button',{name:'1. Generate test plan',exact:true}).click();
  const me=mp.getByRole('button',{name:'2. Execute local tests',exact:true});
  await me.waitFor(); assert(await me.isDisabled());
  await mp.getByRole('checkbox',{name:'I reviewed the expected outcomes against the OpenAPI and business rule.',exact:true}).check();
  await mp.getByRole('checkbox',{name:'I own/control the local test environment and authorize these requests.',exact:true}).check();
  await me.click();
  await mp.getByText('FAIL — overdraft-rule',{exact:true}).waitFor();
  await mp.getByText('FAIL — overdraft-rule',{exact:true}).scrollIntoViewIfNeeded();
  const sizes=await mp.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
  assert(sizes.document<=sizes.viewport+1,JSON.stringify(sizes));
  await mp.screenshot({path:path.join(out,'mobile-evidence.png'),fullPage:true});
  findings.push({check:'mobile_390px_full_flow_no_document_overflow',status:'PASS',sizes});
  await mobile.close();
  fs.writeFileSync(path.join(out,'checks.json'),JSON.stringify({checked_at:new Date().toISOString(),status:'PASS',browser:'Chromium via Playwright; automated, not human QA',meta_inference:'NOT_RUN',elapsed_seconds:(Date.now()-started)/1000,checks:findings},null,2)+'\n');
  console.log(JSON.stringify(findings));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
